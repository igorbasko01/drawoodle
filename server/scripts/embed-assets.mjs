// Writes src/embedded.gen.ts: the built web app (../webapp/dist) inside the Worker script.
// Only for `npm run deploy:embedded`, which deploys without Cloudflare's separate asset upload.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const dist = new URL('../../webapp/dist/', import.meta.url).pathname;
const files = {};
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else files['/' + relative(dist, path)] = readFileSync(path).toString('base64');
  }
};
walk(dist);
writeFileSync(new URL('../src/embedded.gen.ts', import.meta.url), `// Generated by scripts/embed-assets.mjs. Do not edit.\nexport const FILES: Record<string, string> = ${JSON.stringify(files)};\n`);
console.log(`Embedded ${Object.keys(files).length} files from webapp/dist`);
